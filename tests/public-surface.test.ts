describe("public surface", () => {
	it("stays standalone across tracked text files", () => {
		const violations = scanPublicFiles().flatMap((path) => {
			const content = readFileSync(path, "utf8");
			const normalized = content.toLocaleLowerCase("en-US");
			return [
				...blockedFragments
					.filter((fragment) => normalized.includes(fragment))
					.map((fragment) => `${relativePath(path)} -> blocked-fragment:${fragment}`),
				...blockedWords
					.filter((word) => new RegExp(`\\b${escapeRegExp(word)}\\b`, "i").test(content))
					.map((word) => `${relativePath(path)} -> blocked-word:${word}`),
			];
		});

		expect(violations).toEqual([]);
	});
});

function scanPublicFiles(): string[] {
	return trackedFiles().flatMap((entry) => scanTextFiles(join(repoRoot, entry)));
}

function trackedFiles(): string[] {
	return execFileSync("git", ["ls-files"], { cwd: repoRoot, encoding: "utf8" })
		.split("\n")
		.filter(Boolean);
}

function scanTextFiles(path: string): string[] {
	const stats = statSync(path);
	if (stats.isDirectory()) {
		return readdirSync(path).flatMap((entry) => scanTextFiles(join(path, entry)));
	}
	if (stats.isFile() && isTextFile(path)) {
		return guardFiles.has(path) ? [] : [path];
	}
	return [];
}

function isTextFile(path: string): boolean {
	return (
		[".json", ".jsonl", ".md", ".mjs", ".sh", ".ts", ".txt", ".yaml", ".yml"].includes(
			extname(path),
		) || [".editorconfig", ".gitignore"].includes(basename(path))
	);
}

function relativePath(path: string): string {
	return path.slice(`${repoRoot}/`.length);
}

function toText(codePoints: number[]): string {
	return String.fromCodePoint(...codePoints);
}

function escapeRegExp(value: string): string {
	return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
